<h2>Tasks vs. outcomes</h2>
<p>Delegating a <em>task</em> sounds like: "Build the slide deck using this template and send it to me by Thursday."</p>
<p>Delegating an <em>outcome</em> sounds like: "On Friday the leadership team needs to decide whether to fund this project. Your job is to make that decision easy for them. What do you need from me?"</p>
<p>The first gets you a deck. The second gets you a teammate who is thinking like an owner.</p>
<h2>A simple formula</h2>
<ul>
<li><strong>Why</strong> it matters (purpose)</li>
<li><strong>What</strong> success looks like (clarity)</li>
<li><strong>When</strong> you'll check in — not hover (trust)</li>
<li><strong>What</strong> support they can count on (care)</li>
</ul>
<p>Then let them do it differently than you would have. That difference is where they grow.</p>
